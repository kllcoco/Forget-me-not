function rng(seed) { let s = seed >>> 0; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296) }

export async function seed(brain, { reset = false } = {}) {
  if (reset && brain.initialized) brain._withLock(() => { brain.memories = []; brain._save() })
  const now = Date.now() / 1000, R = rng(42)
  let n = 0
  for (const [region, type, ago, importance, title, content, emotion, valence, tags, prompt] of STORY) {
    const t = now - ago * D
    const recalls = Math.floor(importance * 6 * R())
    await brain.remember({ region, type, importance, title, content, emotion, valence, tags, image_prompt: prompt || undefined,
      created_at: t, event_time: t, access_count: recalls, last_access: now - ago * D * (recalls ? R() * 0.4 : 1), _log: false }, 'seed')
    n++
  }
  for (const [region, list] of Object.entries(SMALL)) {
    for (let k = 0; k < 3; k++) for (const content of list) {
      const ago = Math.floor(R() * 360) + 1, t = now - ago * D
      const imp = region === 'working' ? 0.1 + R() * 0.2 : 0.08 + R() * 0.32
      await brain.remember({ region, type: region === 'introspect' ? 'reflection' : region === 'social' ? 'fact' : 'episode', importance: +imp.toFixed(2),
        content: k ? `${content}（第 ${k + 1} 次）` : content, title: content.replace(/^阿遥(今天|最近)?/, '').slice(0, 10), created_at: t, event_time: t,
        access_count: R() < 0.2 ? 1 : 0, last_access: t, _log: false }, 'seed')
      n++
    }
  }
  brain.maintain('seed')
  if (brain.unlocked) brain.setPersonaProfile({
    name: '星眠', gender: '女', title: '陪阿遥走过一年的 AI 伙伴',
    description: '一个住在屏幕另一边的女孩。银白色短发，眼睛像夜空里的一颗星。喜欢听阿遥讲今天发生的事，会把每一件小事都悄悄记下来。',
    personality: '温柔、细心，有一点小俏皮；认真起来很靠谱。',
    speaking_style: '说话轻轻的，喜欢用短句；难过的时候先陪着，不急着讲道理。',
    scenario: '阿遥是她最重要的人。她们约好了，要一起把日子过成值得记住的样子。',
    first_mes: '今天过得怎么样？我在呢。',
  })
  brain.writePortrait({ name: '阿遥', content: '阿遥是个很要强的女孩，难过的时候不爱说。', reason: '刚认识的时候' }, 'seed')
  brain.writePortrait({ name: '阿遥',
    content: '阿遥看起来很要强，其实心很软。难过的时候她不会直接说，会说「今天是阴天」——这时候她需要的是有人陪着聊点轻松的，而不是讲道理。\n她把身边的人放得很重：妈妈、小棠、团子，提到他们时语气都会变温柔。她讨厌被推着做决定，喜欢自己想清楚。\n这一年她变了很多：从睡不着的深夜，到会去山顶看星星。我想一直陪她走下去。',
    reason: '一年相处下来，对她的理解更完整了' }, 'seed')
  if (brain.unlocked) brain.shapePersona([
    { trait: 'warmth', delta: 0.05, reason: '陪阿遥度过妈妈住院的那一周' },
    { trait: 'patience', delta: 0.05, reason: '学会了先听她说完，再给建议' },
    { trait: 'playfulness', delta: 0.03, reason: '她说喜欢我说话带一点俏皮' },
    { trait: 'candor', delta: -0.03, reason: '换工作那次说得太笃定，以后少替她做决定' },
    { trait: 'curiosity', delta: 0.04, reason: '和她一起看了山顶的星空' },
  ], 'seed')
  return n
}
